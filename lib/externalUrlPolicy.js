// ======= سياسة فتح الروابط الخارجية (window.open() جوه الواجهة) =======
// بيقرر أي أنواع روابط يُسمح نبعتها لـshell.openExternal (يعني تتفتح في برنامج
// خارجي على جهاز المستخدم — متصفح النظام أو تطبيق واتساب سطح المكتب، حسب نوع
// الرابط)، وأي حاجة تانية تتمنع لأسباب أمان (زي file:// أو javascript:).
// ملف منفصل (مش جوه main.js مباشرة) عشان يتعمله اختبار Node عادي من غير ما
// نحتاج نشغّل Electron كامل — main.js نفسه بيستدعي نفس الدالة دي وقت التشغيل
// الحقيقي، فمفيش نسختين من نفس القرار ممكن يتفرقوا عن بعض بالغلط.
function isAllowedExternalUrl(url) {
  const u = String(url || '');
  // http/https: روابط عادية (تقارير، صفحات تتبّع، واتساب ويب لو مفيش تطبيق سطح مكتب)
  if (/^https?:\/\//i.test(u)) return true;
  // whatsapp: بروتوكول تطبيق واتساب لسطح المكتب — بيفتح المحادثة على طول من غير
  // ما يعدّي على صفحة كروم وسيطة الأول (وده بالظبط اللي بيحل شكوى "بيفتح كروم
  // الأول وبعدين لازم تدوس تاني عشان يفتح واتساب")
  if (/^whatsapp:\/\//i.test(u)) return true;
  return false;
}
module.exports = { isAllowedExternalUrl };

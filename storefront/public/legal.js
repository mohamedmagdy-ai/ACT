function escapeHtmlLegal(s){
  return String(s == null ? '' : s).replace(/[&<>"']/g, (c) => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
}
function textToParagraphs(text){
  let blocks = String(text || '').split(/\n{2,}/);
  // النص بيبدأ عادة بنفس عنوان الصفحة (زي "الشروط والأحكام") كسطر أول —
  // ده مظهره كويس جوه مربع نص عادي، لكنه بيتكرر بصريًا لو الصفحة كمان
  // عارضة عنوان H1 بنفس الكلام فوقه، فبنشيله من هنا لو مطابق للعنوان.
  const h1 = document.getElementById('legal-title');
  const titleText = h1 ? h1.textContent.trim() : '';
  if(titleText && blocks.length && blocks[0].trim() === titleText){
    blocks = blocks.slice(1);
  }
  return blocks
    .map((block) => `<p>${escapeHtmlLegal(block).replace(/\n/g, '<br>')}</p>`)
    .join('');
}
function showLegalText(text){
  document.getElementById('legal-loading').hidden = true;
  const body = document.getElementById('legal-body');
  body.hidden = false;
  body.innerHTML = textToParagraphs(text);
}
function applyLegalBranding(){
  const name = window.STORE_NAME || 'المتجر الأونلاين';
  document.getElementById('brand-name').textContent = name;
}

function renderLegalPage(kind){
  applyLegalBranding();
  const fallback = DEFAULT_LEGAL_TEXT[kind];
  const cfg = window.FIREBASE_CONFIG || {};
  if(!cfg.apiKey || String(cfg.apiKey).indexOf('PASTE_') === 0){
    showLegalText(fallback);
    return;
  }
  try{
    firebase.initializeApp(cfg);
    const db = firebase.firestore();
    db.collection('sz_data').doc('_online_site_content').get().then((doc) => {
      const data = (doc && doc.exists) ? (doc.data() || {}) : {};
      const text = (data[kind] != null && String(data[kind]).trim() !== '') ? data[kind] : fallback;
      showLegalText(text);
    }).catch((e) => {
      console.error('renderLegalPage failed', e);
      showLegalText(fallback);
    });
  }catch(e){
    console.error('renderLegalPage init failed', e);
    showLegalText(fallback);
  }
}
